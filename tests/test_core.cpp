void CoreTest::renameRules()
{
    using core::RenameRule;
    RenameRule r;  // wildcard, "*" -> "*", keeps everything
    QCOMPARE(core::applyRule(r, QStringLiteral("IMG_0042.JPG"), 0), QStringLiteral("IMG_0042.JPG"));

    r.pattern = QStringLiteral("IMG_*");
    r.replacement = QStringLiteral("holiday_*");
    QCOMPARE(core::applyRule(r, QStringLiteral("IMG_0042.JPG"), 0), QStringLiteral("holiday_0042.JPG"));
    QCOMPARE(core::applyRule(r, QStringLiteral("notes.txt"), 0), QStringLiteral("notes.txt"));  // no match

    r.replacement = QStringLiteral("holiday_{n}");
    r.numberStart = 10;
    r.numberStep = 5;
    r.numberDigits = 3;
    QCOMPARE(core::applyRule(r, QStringLiteral("IMG_0042.JPG"), 2), QStringLiteral("holiday_020.JPG"));

    r.replacement = QStringLiteral("{name}-{ext}");
    QCOMPARE(core::applyRule(r, QStringLiteral("IMG_0042.JPG"), 0), QStringLiteral("IMG_0042-JPG.JPG"));

    r.pattern = QStringLiteral("*");
    r.replacement = QStringLiteral("*");
    r.caseChange = RenameRule::Case::Lower;
    QCOMPARE(core::applyRule(r, QStringLiteral("IMG_0042.JPG"), 0), QStringLiteral("img_0042.JPG"));
    r.ignoreExtension = false;
    QCOMPARE(core::applyRule(r, QStringLiteral("IMG_0042.JPG"), 0), QStringLiteral("img_0042.jpg"));
    r.caseChange = RenameRule::Case::Title;
    QCOMPARE(core::applyRule(r, QStringLiteral("my holiday photos.jpg"), 0), QStringLiteral("My Holiday Photos.Jpg"));

    RenameRule re;
    re.mode = RenameRule::Mode::Regex;
    re.pattern = QStringLiteral("^(\\d+)-(.*)$");
    re.replacement = QStringLiteral("\\2 (\\1)");
    QCOMPARE(core::applyRule(re, QStringLiteral("01-intro.mp3"), 0), QStringLiteral("intro (01).mp3"));

    RenameRule rep;
    rep.mode = RenameRule::Mode::Replace;
    rep.pattern = QStringLiteral(" ");
    rep.replacement = QStringLiteral("_");
    QCOMPARE(core::applyRule(rep, QStringLiteral("a b c.txt"), 0), QStringLiteral("a_b_c.txt"));

    // Plan: clashes within the batch and with bystanders.
    RenameRule all;
    all.pattern = QStringLiteral("*");
    all.replacement = QStringLiteral("x");
    const core::RenamePlan plan = core::planRename(all, {QStringLiteral("a.txt"), QStringLiteral("b.txt"), QStringLiteral("c.md")},
                                                   {QStringLiteral("a.txt"), QStringLiteral("b.txt"), QStringLiteral("c.md"), QStringLiteral("x.md")});
    QCOMPARE(plan.newNames, QStringList({"x.txt", "x.txt", "x.md"}));
    QVERIFY(plan.clash[0] && plan.clash[1]);  // duplicate within the batch
    QVERIFY(plan.clash[2]);                   // x.md exists and is not being renamed
    QCOMPARE(plan.changed, 3);

    const QString text = re.serialize();
    const RenameRule back = RenameRule::deserialize(text);
    QCOMPARE(back.mode, RenameRule::Mode::Regex);
    QCOMPARE(back.pattern, re.pattern);
    QCOMPARE(back.replacement, re.replacement);
}

void CoreTest::compareTrees()
{
    QTemporaryDir tmp;
    QVERIFY(tmp.isValid());
    const QString L = tmp.path() + "/left";
    const QString R = tmp.path() + "/right";
    QVERIFY(QDir().mkpath(L + "/both/deep"));
    QVERIFY(QDir().mkpath(R + "/both/deep"));
    QVERIFY(QDir().mkpath(L + "/only-left"));
    QVERIFY(QDir().mkpath(R + "/only-right"));
    touch(L + "/same.txt", "same");
    touch(R + "/same.txt", "same");
    touch(L + "/bigger.txt", "123456");
    touch(R + "/bigger.txt", "12");
    touch(L + "/both/deep/a.txt", "a");
    touch(L + "/left-file.txt", "x");
    touch(R + "/both/deep/b.txt", "b");
    touch(L + "/content.txt", "aaaa");
    touch(R + "/content.txt", "bbbb");
    // Same size, same content, but an old timestamp on the right.
    touch(L + "/older-right.txt", "zz");
    touch(R + "/older-right.txt", "zz");
    struct utimbuf old = {1000000000, 1000000000};
    QVERIFY(::utime(QFile::encodeName(R + "/older-right.txt").constData(), &old) == 0);
    // Equal mtimes for the content pair, so only a hash tells them apart.
    struct utimbuf fixed = {1500000000, 1500000000};
    QVERIFY(::utime(QFile::encodeName(L + "/content.txt").constData(), &fixed) == 0);
    QVERIFY(::utime(QFile::encodeName(R + "/content.txt").constData(), &fixed) == 0);
    QVERIFY(::utime(QFile::encodeName(L + "/same.txt").constData(), &fixed) == 0);
    QVERIFY(::utime(QFile::encodeName(R + "/same.txt").constData(), &fixed) == 0);

    auto compare = [&](bool hash) {
        core::Comparer comparer;
        std::vector<core::CompareEntry> got;
        bool done = false;
        connect(&comparer, &core::Comparer::finished, [&](quint64 gen, std::vector<core::CompareEntry> e) {
            QCOMPARE(gen, 4u);
            got = std::move(e);
            done = true;
        });
        core::CompareOptions o;
        o.hash = hash;
        comparer.start(core::Location::fromPath(QFile::encodeName(L)), core::Location::fromPath(QFile::encodeName(R)), o, 4);
        while (!done)
            QTest::qWait(5);
        QHash<QString, core::Difference> byName;
        for (const auto& e : got)
            byName.insert(e.display, e.difference);
        return byName;
    };
    const auto plain = compare(false);
    QCOMPARE(plain.value("same.txt"), core::Difference::Same);
    QCOMPARE(plain.value("bigger.txt"), core::Difference::SizeDiffers);
    QCOMPARE(plain.value("only-left"), core::Difference::LeftOnly);
    QCOMPARE(plain.value("only-right"), core::Difference::RightOnly);
    QCOMPARE(plain.value("left-file.txt"), core::Difference::LeftOnly);
    QCOMPARE(plain.value("both/deep/a.txt"), core::Difference::LeftOnly);
    QCOMPARE(plain.value("both/deep/b.txt"), core::Difference::RightOnly);
    QCOMPARE(plain.value("older-right.txt"), core::Difference::LeftNewer);
    QCOMPARE(plain.value("content.txt"), core::Difference::Same);  // same size and time
    QVERIFY(!plain.contains("both"));  // descended, not listed
    const auto hashed = compare(true);
    QCOMPARE(hashed.value("content.txt"), core::Difference::ContentDiffers);
    QCOMPARE(hashed.value("same.txt"), core::Difference::Same);
}

void CoreTest::archiveListing()
{
    const QByteArray sample =
        "drwxr-xr-x  0 michal michal      0 Oct 30 12:14 src/\n"
        "-rw-r--r--  0 michal michal      3 Oct 30 12:14 src/a.txt\n"
        "-rw-r--r--  0 michal michal      4 Oct 30 12:14 src/sub/with space.txt\n"
        "lrwxrwxrwx  0 michal michal      0 Jan  5  2021 src/link -> a.txt\n"
        "garbage line\n";
    const auto entries = core::parseArchiveListing(sample, 2026);
    QCOMPARE(entries.size(), 4u);
    QCOMPARE(entries[0].path, QByteArray("src"));
    QVERIFY(entries[0].isDir);
    QCOMPARE(entries[1].size, 3u);
    QCOMPARE(entries[2].path, QByteArray("src/sub/with space.txt"));
    QCOMPARE(QDateTime::fromSecsSinceEpoch(entries[2].modified).date(), QDate(2026, 10, 30));
    QVERIFY(entries[3].symlink);
    QCOMPARE(entries[3].path, QByteArray("src/link"));
    QCOMPARE(QDateTime::fromSecsSinceEpoch(entries[3].modified).date(), QDate(2021, 1, 5));
    QVERIFY(core::isArchiveName("photos.ZIP"));
    QVERIFY(core::isArchiveName("backup.tar.zst"));
    QVERIFY(!core::isArchiveName("notes.txt"));

    // A real archive through bsdtar, then one member extracted.
    QTemporaryDir tmp;
    QVERIFY(tmp.isValid());
    QVERIFY(QDir().mkpath(tmp.path() + "/src/sub"));
    touch(tmp.path() + "/src/a.txt", "hello");
    touch(tmp.path() + "/src/sub/b.txt", "world!");
    QProcess tar;
    tar.setWorkingDirectory(tmp.path());
    tar.start(QStringLiteral("bsdtar"), {QStringLiteral("-cf"), QStringLiteral("demo.zip"), QStringLiteral("src")});
    if (!tar.waitForFinished(10000) || tar.exitCode() != 0)
        QSKIP("bsdtar not available");
    const core::Location zip = core::Location::fromPath(QFile::encodeName(tmp.path() + "/demo.zip"));

    core::ArchiveLister lister;
    std::vector<core::ArchiveEntry> listed;
    bool done = false;
    connect(&lister, &core::ArchiveLister::listed, [&](quint64, std::vector<core::ArchiveEntry> e) { listed = e; done = true; });
    connect(&lister, &core::ArchiveLister::failed, [&](quint64, const QString& m) { QFAIL(qPrintable(m)); });
    lister.start(zip, 1);
    while (!done)
        QTest::qWait(5);
    QStringList paths;
    for (const auto& e : listed)
        paths << QString::fromUtf8(e.path);
    paths.sort();
    QCOMPARE(paths, QStringList({"src", "src/a.txt", "src/sub", "src/sub/b.txt"}));

    QVERIFY(QDir().mkpath(tmp.path() + "/out"));
    core::ExtractJob job(zip, {QByteArray("src/sub/b.txt")}, core::Location::fromPath(QFile::encodeName(tmp.path() + "/out")), 2);
    QSignalSpy finished(&job, &core::Job::finished);
    job.start();
    while (finished.isEmpty())
        QTest::qWait(5);
    QVERIFY2(job.log().empty(), job.log().empty() ? "" : qPrintable(job.log().front().message));
    QFile out(tmp.path() + "/out/b.txt");
    QVERIFY(out.open(QIODevice::ReadOnly));
    QCOMPARE(out.readAll(), QByteArray("world!"));
}

